export const STOP_WORDS: ReadonlySet<string> = new Set([
  ...ENGLISH_STOP_WORDS,
  ...URDU_STOP_WORDS,
  ...HINDI_STOP_WORDS,
]);

export interface RetrievalQuery {
  /** Distinct meaningful terms (lower-case unicode word tokens, never tsquery syntax). */
  terms: string[];
  /** Number of distinct terms a row must contain; 0 when there are no terms (abstain). */
  minMatches: number;
}

/** Tokenise, drop stop words and very short tokens, and derive the minimum-match rule. */
export function buildRetrievalQuery(question: string): RetrievalQuery {
  const tokens = question.toLowerCase().match(/[\p{L}\p{M}\p{N}]{1,40}/gu) ?? [];
  const terms: string[] = [];
  for (const token of tokens) {
    if ([...token].length < MIN_TERM_LENGTH || STOP_WORDS.has(token) || terms.includes(token))
      continue;
    terms.push(token);
    if (terms.length === MAX_QUERY_TERMS) break;
  }
  if (!terms.length) return { terms, minMatches: 0 };
  return {
    terms,
    minMatches: terms.length >= MANY_TERMS_THRESHOLD ? MIN_MATCHES_MANY : MIN_MATCHES_FEW,
  };
}
